/**
 * Generates `src/app/shared/ui/brand-registry.ts` from an Iconify export of
 * Simple Icons (CC0-1.0). Only the single `d` attribute of each 24×24 icon is
 * kept, after a strict path-data check, so the registry can never carry markup.
 *
 * Usage:
 *   curl -o /tmp/si/icons.json "https://api.iconify.design/simple-icons.json?icons=<slugs>"
 *   curl -o /tmp/si/info.json  "https://api.iconify.design/collection?prefix=simple-icons&info=true"
 *   node scripts/gen-brand-registry.mjs /tmp/si/icons.json /tmp/si/info.json
 *
 * The slugs are the keys of BRANDS below; add one there before regenerating.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const BRANDS = [
  'postgresql', 'mysql', 'mariadb', 'microsoftsqlserver', 'oracle', 'sap', 'microsoftazure',
  'snowflake', 'googlebigquery', 'amazonredshift', 'databricks', 'amazons3', 'minio',
  'googlecloudstorage', 'microsoftsharepoint', 'microsoftonedrive', 'mongodb', 'elasticsearch',
  'opensearch', 'apachecassandra', 'modelcontextprotocol', 'openapiinitiative', 'github',
  'notion', 'atlassian', 'huggingface', 'dynamics365', 'microsoftteams', 'microsoftoutlook',
  'telegram', 'whatsapp', 'mqtt', 'openai', 'anthropic', 'ollama',
];

const [iconsPath, infoPath] = process.argv.slice(2);
if (!iconsPath || !infoPath) {
  console.error('usage: node scripts/gen-brand-registry.mjs <icons.json> <info.json>');
  process.exit(2);
}
const icons = JSON.parse(readFileSync(iconsPath, 'utf8'));
const info = JSON.parse(readFileSync(infoPath, 'utf8')).info ?? {};
if (icons.prefix !== 'simple-icons' || icons.width !== 24 || icons.height !== 24) {
  throw new Error('expected a 24×24 simple-icons export');
}
if (info.license?.spdx !== 'CC0-1.0' || !/^\d+\.\d+\.\d+$/.test(String(info.version))) {
  throw new Error('expected Simple Icons CC0-1.0 with a semantic version');
}
const BODY = /^<path fill="currentColor" d="([^"]+)"\/>$/;
const PATH_DATA = /^[MmZzLlHhVvCcSsQqTtAa0-9eE.,\-\s]{1,20000}$/;
const lines = BRANDS.map((slug) => {
  const body = icons.icons?.[slug]?.body;
  const match = typeof body === 'string' ? BODY.exec(body) : null;
  if (!match || !PATH_DATA.test(match[1])) throw new Error(`missing or unsafe icon: ${slug}`);
  return `  ${slug}: '${match[1]}',`;
});

const here = dirname(fileURLToPath(import.meta.url));
const target = join(here, '..', 'src', 'app', 'shared', 'ui', 'brand-registry.ts');
writeFileSync(
  target,
  `/**
 * Brand logos for connector and provider cards: Simple Icons ${info.version} (CC0-1.0),
 * 24×24, single path, monochrome (\`currentColor\`). Generated by
 * \`scripts/gen-brand-registry.mjs\`; do not edit by hand.
 *
 * The logos are the trademarks of their owners. They identify the product a
 * connector talks to; they do not imply endorsement, and each brand's own
 * guidelines apply.
 */

export const BRAND_ICONS_VERSION = 'simple-icons@${info.version}';

export const BRAND_PATHS = {
${lines.join('\n')}
} as const;

export type BrandIconName = keyof typeof BRAND_PATHS;

export function brandPath(name: string): string | null {
  return Object.prototype.hasOwnProperty.call(BRAND_PATHS, name)
    ? BRAND_PATHS[name as BrandIconName]
    : null;
}
`,
);
console.log(`wrote ${BRANDS.length} brand paths to ${target}`);
