"""Opt-in real PG/Temporal mechanics qualification, never production activation.

Run with the isolated requirements_orchestration environment, PYTHONPATH=.
The deterministic port below is explicitly a test double: its rows are neither
SkillInvocations nor DeliveryReceipts. Passing does not qualify O5/providers.
The disposable database schema is generated by this script and always removed.
"""
