class QualificationPort:
    """Durable idempotent *fixture* with current-policy checks, no real provider."""
    def __init__(self, dsn):
        self.dsn, self.active = dsn, 0

    def setup(self):
        with psycopg.connect(self.dsn) as db:
            db.execute("CREATE TABLE qualification_controls (run_id text PRIMARY KEY, scope jsonb NOT NULL, enabled boolean NOT NULL DEFAULT true, approved boolean NOT NULL DEFAULT false, fail_before text, fail_after text, budget integer NOT NULL DEFAULT 100)")
            db.execute("CREATE TABLE qualification_effects (operation_key text PRIMARY KEY, run_id text NOT NULL, node text NOT NULL, status text NOT NULL, attempts integer NOT NULL DEFAULT 1, value integer)")

    def create(self, scope, *, fail_before=None, fail_after=None, budget=100):
        from psycopg.types.json import Jsonb
        with psycopg.connect(self.dsn) as db:
            db.execute("INSERT INTO qualification_controls(run_id,scope,fail_before,fail_after,budget) VALUES(%s,%s,%s,%s,%s)", (scope.run_id, Jsonb(scope.to_dict()), fail_before, fail_after, budget))

    def change(self, run_id, *, approved=None, enabled=None):
        with psycopg.connect(self.dsn) as db:
            if approved is not None:
                db.execute("UPDATE qualification_controls SET approved=%s WHERE run_id=%s", (approved, run_id))
            if enabled is not None:
                db.execute("UPDATE qualification_controls SET enabled=%s WHERE run_id=%s", (enabled, run_id))

    async def authorize(self, scope):
        with psycopg.connect(self.dsn) as db:
            row = db.execute("SELECT scope,enabled FROM qualification_controls WHERE run_id=%s", (scope.run_id,)).fetchone()
            if not row or row[0] != scope.to_dict() or not row[1]:
                raise PermissionError("QUALIFICATION_ACCESS_REVOKED")

    async def submit(self, scope, node_id, operation_key):
        await self.authorize(scope)
        self.active += 1
        fail = None
        try:
            with psycopg.connect(self.dsn) as db:
                control = db.execute("SELECT fail_before,fail_after,budget,approved FROM qualification_controls WHERE run_id=%s FOR UPDATE", (scope.run_id,)).fetchone()
                if control[0] == node_id:
                    db.execute("UPDATE qualification_controls SET fail_before=NULL WHERE run_id=%s", (scope.run_id,))
                    fail = "QUALIFICATION_FAIL_BEFORE_EFFECT"
                else:
                    existing = db.execute("SELECT run_id,node FROM qualification_effects WHERE operation_key=%s", (operation_key,)).fetchone()
                    if existing and existing != (scope.run_id, node_id):
                        raise ValueError("QUALIFICATION_IDENTITY_CONFLICT")
                    if not existing:
                        count = db.execute("SELECT count(*) FROM qualification_effects WHERE run_id=%s", (scope.run_id,)).fetchone()[0]
                        if count >= control[2]:
                            raise RuntimeError("QUALIFICATION_BUDGET_EXCEEDED")
                        if node_id == "delivery" and not control[3]:
                            raise PermissionError("QUALIFICATION_REVIEW_REQUIRED")
                    # Tiny deterministic SQL fixture, not a DataOps volume run.
                    value = db.execute("SELECT sum(v) FROM generate_series(1,10) v").fetchone()[0] if node_id == "data_prepare" else None
                    db.execute("INSERT INTO qualification_effects(operation_key,run_id,node,status,value) VALUES(%s,%s,%s,%s,%s) ON CONFLICT(operation_key) DO UPDATE SET attempts=qualification_effects.attempts+1", (operation_key, scope.run_id, node_id, "waiting" if node_id == "review" else "succeeded", value))
                    if control[1] == node_id:
                        db.execute("UPDATE qualification_controls SET fail_after=NULL WHERE run_id=%s", (scope.run_id,))
                        fail = "QUALIFICATION_FAIL_AFTER_EFFECT_COMMIT"
            if fail:
                raise RuntimeError(fail)
            kind = "decision" if node_id == "review" else "delivery_receipt" if node_id == "delivery" else "recipe_execution" if node_id == "data_prepare" else "run"
            return NativeReference(kind, operation_key, scope.workspace_id, scope.run_id)
        finally:
            self.active -= 1

    async def observe(self, scope, reference):
        await self.authorize(scope)
        if (reference.workspace_id, reference.run_id) != (scope.workspace_id, scope.run_id):
            raise ValueError("QUALIFICATION_SCOPE_MISMATCH")
        with psycopg.connect(self.dsn) as db:
            row = db.execute("SELECT node,status FROM qualification_effects WHERE operation_key=%s AND run_id=%s", (reference.id, scope.run_id)).fetchone()
            if row[0] == "review" and db.execute("SELECT approved FROM qualification_controls WHERE run_id=%s", (scope.run_id,)).fetchone()[0]:
                db.execute("UPDATE qualification_effects SET status='succeeded' WHERE operation_key=%s", (reference.id,))
                row = (row[0], "succeeded")
            return NativeState(row[1], reference)

    def evidence(self, run_id):
        with psycopg.connect(self.dsn) as db:
            rows = db.execute("SELECT node,status,attempts,value FROM qualification_effects WHERE run_id=%s ORDER BY node", (run_id,)).fetchall()
        return {"fixture_effects": len(rows), "effects": [{"node": n, "status": s, "attempts": a, "value": v} for n,s,a,v in rows], "active_adapter_calls": self.active}


def scope(label):
    return ExecutionScope("qualification-workspace", f"{label}-{uuid4().hex}", "qualification-actor", "frozen-v1", "a"*64)


async def wait_for_review(handle):
    deadline = time.monotonic() + 25
    while time.monotonic() < deadline:
        if await handle.query(ComposedNativeWorkflow.awaiting_native):
            description = await handle.describe()
            assert not description.raw_description.pending_activities
            return
        await asyncio.sleep(0.05)
    raise TimeoutError("REVIEW_NOT_REACHED")


async def langgraph_cases(port, dsn):
    cases = []
    for name in COMPOSITIONS:
        item = scope("langgraph")
        port.create(item)
        initial = await invoke(dsn, name, item)
        assert initial.get("__interrupt__") and port.active == 0
        # Reconstruct the saver and graph after the pause: no in-memory saver.
        configure_port(QualificationPort(dsn))
        port.change(item.run_id, approved=True)
        result = await invoke(dsn, name, item, resume=True)
        assert len(result["references"]) == 5
        assert port.evidence(item.run_id)["fixture_effects"] == 5
        cases.append({"case": name+"_durable_review_reopen", "passed": True, **port.evidence(item.run_id)})
        configure_port(port)
    for failure in ("before", "after"):
        item = scope("langgraph-fault")
        port.create(item, **{"fail_"+failure: "data_prepare"})
        try:
            await invoke(dsn, "agent_data_agent", item)
            raise AssertionError("injected failure not observed")
        except RuntimeError as exc:
            assert str(exc).startswith("QUALIFICATION_FAIL_")
        result = await invoke(dsn, "agent_data_agent", item, recover=True)
        assert result.get("__interrupt__")
        port.change(item.run_id, approved=True)
        result = await invoke(dsn, "agent_data_agent", item, resume=True)
        assert len(result["references"]) == 5 and port.evidence(item.run_id)["fixture_effects"] == 5
        cases.append({"case": "failure_"+failure+"_effect_recovery", "passed": True, **port.evidence(item.run_id)})
    item = scope("langgraph-revoked")
    port.create(item)
    await invoke(dsn, "data_agent_delivery", item)
    port.change(item.run_id, enabled=False, approved=True)
    try:
        await invoke(dsn, "data_agent_delivery", item, resume=True)
        raise AssertionError("revocation bypassed")
    except PermissionError:
        assert "delivery" not in {row["node"] for row in port.evidence(item.run_id)["effects"]}
    cases.append({"case": "revoked_before_resume", "passed": True})
    return cases


async def temporal_cases(port, endpoint, restart_container=None):
    client = await Client.connect(endpoint)
    task_queue = "qualification-" + uuid4().hex
    def worker():
        return Worker(client, task_queue=task_queue, workflows=[ComposedNativeWorkflow], plugins=[plugin()], max_concurrent_activities=2, max_concurrent_workflow_tasks=2, max_cached_workflows=0)
    cases, suspended = [], []
    async with worker():
        for name in COMPOSITIONS:
            item = scope("temporal")
            port.create(item, fail_after="data_prepare")
            handle = await client.start_workflow(ComposedNativeWorkflow.run, {"composition": name, "scope": item.to_dict()}, id=item.run_id, task_queue=task_queue, execution_timeout=timedelta(seconds=90))
            await wait_for_review(handle)
            assert port.active == 0
            suspended.append((name, item, handle))
    if restart_container:
        if restart_container != "test_obs_temporal":
            raise ValueError("ONLY_DISPOSABLE_QUALIFICATION_CONTAINER_ALLOWED")
        subprocess.run(["docker", "restart", restart_container], check=True, capture_output=True, timeout=30)
        # The bounded query retries observe server readiness; no fixed sleep
        # is mistaken for confirmation that history survived its restart.
        deadline = time.monotonic()+25
        while True:
            try:
                await client.service_client.check_health()
                break
            except Exception:
                if time.monotonic() >= deadline:
                    raise
                await asyncio.sleep(0.1)
    # A new Worker replays from Temporal history. No PostgreSQL checkpointer is
    # registered with this plugin and no original worker cache is retained.
    async with worker():
        for name, item, handle in suspended:
            await wait_for_review(handle)
            port.change(item.run_id, approved=True)
            await handle.signal(ComposedNativeWorkflow.native_changed)
            result = await asyncio.wait_for(handle.result(), 30)
            assert len(result["references"]) == 5
            proof = port.evidence(item.run_id)
            assert proof["fixture_effects"] == 5
            assert next(row for row in proof["effects"] if row["node"] == "data_prepare")["attempts"] == 2
            cases.append({"case": name+"_retry_after_commit_review_worker_restart", "passed": True, "server_restarted": bool(restart_container), "pending_activities_during_review": 0, **proof})
        for mode in ("revoked", "cancelled", "budget", "duplicate_before_effect"):
            item = scope("temporal-"+mode)
            port.create(item, budget=2 if mode == "budget" else 100, fail_before="data_prepare" if mode == "duplicate_before_effect" else None)
            request = {"composition": "data_agent_delivery", "scope": item.to_dict()}
            handle = await client.start_workflow(ComposedNativeWorkflow.run, request, id=item.run_id, task_queue=task_queue, execution_timeout=timedelta(seconds=90))
            if mode == "budget":
                try:
                    await asyncio.wait_for(handle.result(), 25)
                    raise AssertionError("budget bypassed")
                except WorkflowFailureError:
                    assert port.evidence(item.run_id)["fixture_effects"] == 2
            else:
                await wait_for_review(handle)
                if mode == "revoked":
                    port.change(item.run_id, enabled=False, approved=True)
                    await handle.signal(ComposedNativeWorkflow.native_changed)
                    try:
                        await asyncio.wait_for(handle.result(), 25)
                        raise AssertionError("revocation bypassed")
                    except WorkflowFailureError:
                        pass
                elif mode == "cancelled":
                    await handle.cancel()
                    try:
                        await asyncio.wait_for(handle.result(), 25)
                        raise AssertionError("cancellation ignored")
                    except WorkflowFailureError as exc:
                        assert isinstance(exc.cause, CancelledError)
                else:
                    try:
                        await client.start_workflow(ComposedNativeWorkflow.run, request, id=item.run_id, task_queue=task_queue)
                        raise AssertionError("duplicate workflow admitted")
                    except WorkflowAlreadyStartedError:
                        pass
                    port.change(item.run_id, approved=True)
                    await handle.signal(ComposedNativeWorkflow.native_changed)
                    await asyncio.wait_for(handle.result(), 25)
            proof = port.evidence(item.run_id)
            if mode != "duplicate_before_effect":
                assert "delivery" not in {row["node"] for row in proof["effects"]}
            cases.append({"case": mode, "passed": True, **proof})
    return cases


async def qualify(args):
    schema = "runtime_probe_" + uuid4().hex
    base_dsn = args.postgres.replace("postgresql+psycopg2://", "postgresql://")
    with psycopg.connect(base_dsn, autocommit=True) as db:
        db.execute(sql.SQL("CREATE SCHEMA {}").format(sql.Identifier(schema)))
    dsn = make_conninfo(base_dsn, options=f"-csearch_path={schema}")
    report = {"scope": "local mechanics with deterministic qualification port", "production_enabled": False,
              "versions": {name: importlib.metadata.version(name) for name in ("langgraph", "langgraph-checkpoint-postgres", "temporalio", "temporalio-langgraph", "psycopg")},
              "native_providers_qualified": False, "native_delivery_receipt_qualified": False,
              "comparison": {"baseline_native_same_corpus": "NOT_PERFORMED",
                             "historical_native_tests": "138 passed previously; not a comparative mechanics run"},
              "coverage_limits": ["deterministic fixture port, not production Skill submission",
                                  "no provider calls, DataOps volume or native DeliveryReceipt publication",
                                  "not the complete native failure, capacity, IAM or cost corpus",
                                  "fixture timings and process RSS are not a production SLA"],
              "gates": {"O5": "NO_GO_NATIVE_SUBMISSION_ADAPTER_UNQUALIFIED"}}
    started = time.monotonic()
    try:
        port = QualificationPort(dsn)
        port.setup()
        configure_port(port)
        for name, function in (("langgraph_postgres", lambda: langgraph_cases(port, dsn)), ("temporal_langgraph", lambda: temporal_cases(port, args.temporal, args.restart_temporal_container))):
            began = time.monotonic()
            try:
                cases = await asyncio.wait_for(function(), 150)
                report[name] = {"cases": cases, "passed": True, "elapsed_seconds": time.monotonic()-began}
            except Exception as exc:
                # These messages originate solely from disposable fixture/SDK
                # mechanics. No production payloads or credentials are passed.
                report[name] = {"passed": False, "error_type": type(exc).__name__, "error": str(exc)[:600], "elapsed_seconds": time.monotonic()-began}
        report["gates"]["langgraph_autonomous"] = "NO_GO_DURABLE_DISPATCH_AND_RECOVERY_INTEGRATION_UNQUALIFIED"
        report["gates"]["temporal_production"] = "NO_GO_PUBLIC_PREVIEW_AND_INCOMPLETE_NATIVE_FAULT_CORPUS"
    finally:
        configure_port(None)
        with psycopg.connect(base_dsn, autocommit=True) as db:
            db.execute(sql.SQL("DROP SCHEMA {} CASCADE").format(sql.Identifier(schema)))
        report["elapsed_seconds"] = time.monotonic()-started
        raw_rss = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
        report["process_peak_rss_bytes"] = raw_rss if sys.platform == "darwin" else raw_rss*1024
        report["cleanup"] = {"postgres_schema_dropped": True}
        Path(args.output).write_text(json.dumps(report, indent=2)+"\n")
    print(json.dumps(report, indent=2))
    return 0 if report.get("langgraph_postgres", {}).get("passed") and report.get("temporal_langgraph", {}).get("passed") else 1


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--postgres", required=True, help="Disposable local PostgreSQL DSN; generated schema only")
    parser.add_argument("--temporal", default="127.0.0.1:17233")
    parser.add_argument("--output", required=True)
    parser.add_argument("--restart-temporal-container", choices=["test_obs_temporal"])
    raise SystemExit(asyncio.run(qualify(parser.parse_args())))
